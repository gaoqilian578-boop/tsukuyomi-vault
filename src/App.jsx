function PasswordGate({ onUnlock }) {
  const [value, setValue] = useState("");
  const [error, setError] = useState("");

  function submit(event) {
    event.preventDefault();
    if (value.trim() === PASS_PHRASE) {
      setError("");
      onUnlock();
      navigate("/");
      return;
    }
    setError("合言葉が違います。LINEに届いた言葉をもう一度確認してください。");
  }

  return (
    <section className="gate-screen">
      <div className="brand-mark">
        <Moon size={24} />
      </div>
      <p className="eyebrow">tsukuyomi vault</p>
      <h1>月読｜夜の保管庫</h1>
      <p className="lead">
        ここは、誰にも言えない恋を
        <br />
        静かに整理するための保管庫です。
      </p>
      <p className="subtle">LINEで届いた合言葉を入力してください。</p>
      <form className="pass-form" onSubmit={submit}>
        <label>
          <span>合言葉</span>
          <input
            value={value}
            onChange={(event) => setValue(event.target.value)}
            placeholder="合言葉を入力"
            autoComplete="off"
          />
        </label>
        {error && <p className="error-message">{error}</p>}
        <button type="submit">
          <LockKeyhole size={18} />
          保管庫を開く
        </button>
      </form>
    </section>
  );
}

